"""Rebuild docs/Home.md, the index of the Obsidian vault: every note in docs/notes/ by type and status, from its frontmatter.
Run after adding or closing a note: python -m tools.misc.doc_index. Conventions: docs/agents/writing-notes.md."""
import os
import re
from collections import defaultdict

DOCS = os.path.join(os.path.dirname(__file__), '..', '..', 'docs')
STATUS_ORDER = ['open', 'review', 'adopted', 'finding', 'rejected', 'closed', 'superseded', 'final', 'archived']
SECTIONS = [('card', 'Cards'), ('report', 'Reports'), ('decision', 'Decisions'), ('reference', 'Papers'), ('guide', 'Guides'), ('note', 'Other notes')]


def read(path):
    text = open(path).read()
    m = re.match(r'---\n(.*?)\n---\n', text, re.S)
    meta = dict(re.findall(r'^(\w+): *(.*)$', m.group(1), re.M)) if m else {}
    title = re.search(r'^# (.+)$', text, re.M)
    return meta, (title.group(1).strip() if title else os.path.basename(path)[:-3])


def row(name, meta, title, status=True):
    cells = [meta.get('date', ''), f'[[{name}|{title[:110]}]]']
    if status: cells.append(meta.get('status', ''))
    cells.append(meta.get('tags', '').strip('[]'))
    return '| ' + ' | '.join(cells) + ' |'


def main():
    notes = defaultdict(list); tags = defaultdict(list)
    paths = [(r, f) for r, _, fs in sorted(os.walk(os.path.join(DOCS, 'notes'))) for f in sorted(fs)] + [(os.path.join(DOCS, 'agents'), f) for f in sorted(os.listdir(os.path.join(DOCS, 'agents')))]
    for folder, f in paths:
        if True:
            if f.endswith('.md'):
                meta, title = read(os.path.join(folder, f)); name = f[:-3]
                notes[meta.get('type', 'note')].append((name, meta, title))
                for t in re.findall(r'[\w-]+', meta.get('tags', '')): tags[t].append(name)
    out = ['---', 'type: guide', 'tags: [guide]', '---', '# Qlet notes', '',
           f'{sum(len(v) for v in notes.values())} notes. Generated by `python -m tools.misc.doc_index`; do not edit. How to write one: [[writing-notes]]. '
           'Templates: `_templates/`. Newest first within a status.', '']
    for typ, head in SECTIONS:
        items = notes.get(typ, [])
        if not items: continue
        out += [f'## {head}', '']
        if typ in ('card', 'decision'):
            by = defaultdict(list)
            for it in items: by[it[1].get('status', 'review')].append(it)
            for st in STATUS_ORDER:
                if st not in by: continue
                out += [f'### {head} {st}', '', '| date | note | tags |', '|---|---|---|']
                out += [row(n, m, t, False) for n, m, t in sorted(by[st], key=lambda x: x[1].get('date', x[0]), reverse=True)] + ['']
        else:
            out += ['| date | note | status | tags |', '|---|---|---|---|']
            out += [row(n, m, t) for n, m, t in sorted(items, key=lambda x: x[1].get('date', x[0]), reverse=True)] + ['']
    out += ['## Tags', '']
    for t in sorted(tags): out.append(f'- **{t}** ({len(tags[t])}): ' + ', '.join(f'[[{n}]]' for n in tags[t][:6]) + (' ...' if len(tags[t]) > 6 else ''))
    open(os.path.join(DOCS, 'Home.md'), 'w').write('\n'.join(out) + '\n')
    print(f'docs/Home.md: {sum(len(v) for v in notes.values())} notes')


if __name__ == '__main__':
    main()
